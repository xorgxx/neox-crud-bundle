<?php

declare(strict_types=1);

namespace Neox\NeoxCrudBundle\DependencyInjection;

use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

class Configuration implements ConfigurationInterface
{
    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder('neox_crud');

        $rootNode = $treeBuilder->getRootNode();
        $rootNode
            ->children()
                ->scalarNode('uploads_dir')
                    ->defaultValue('public/uploads') // Default value
                    ->info('The directory where files are uploaded')
                ->end()
            ->end()
            ->children()
                ->arrayNode('mercure')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')
                            ->defaultTrue()
                        ->end()
                        ->scalarNode('topic_prefix')
                            ->defaultValue('/crud')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('makers')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')
                            ->defaultTrue()
                        ->end()
                        ->scalarNode('templates_namespace')
                            ->defaultNull()
                            ->info('Default Twig namespace used by the Maker when generating templates (can be overridden by CLI option).')
                        ->end()
                        ->scalarNode('base_layout')
                            ->defaultNull()
                            ->info('Default Twig base layout path used by the Maker when generating templates (can be overridden by CLI option). When null, falls back to /admin/_layout.html.twig or namespace-derived value.')
                        ->end()
                        ->scalarNode('content_block')
                            ->defaultValue('content')
                            ->info('Twig block name where NeoxCrud templates will render their content (e.g. content, body, admin_content).')
                        ->end()
                        ->arrayNode('relations')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->enumNode('mode')
                                    ->values(['mix', 'interactive'])
                                    ->defaultValue('mix')
                                    ->info('mix: questions only if ambiguous (default). interactive: always ask for relations.')
                                ->end()
                                ->enumNode('default_render')
                                    ->values(['select', 'autocomplete', 'checkbox'])
                                    ->defaultValue('select')
                                    ->info('Default render type for Doctrine relation fields generated by the Maker (ManyToOne/ManyToMany/OneToOne).')
                                ->end()
                                ->arrayNode('choice_label_priority')
                                    ->prototype('scalar')->end()
                                    ->defaultValue(['name', 'title', 'label', 'id'])
                                    ->info('Priority order for detecting the best choice_label field on related entities.')
                                ->end()
                                ->booleanNode('nullable_required')
                                    ->defaultFalse()
                                    ->info('If false, nullable relations are generated with required=false.')
                                ->end()
                                ->enumNode('order')
                                    ->values(['end', 'interleaved', 'start'])
                                    ->defaultValue('interleaved')
                                    ->info('Order of relation fields in generated forms.')
                                ->end()
                                ->booleanNode('group_relations')
                                    ->defaultTrue()
                                    ->info('If true, the Maker may group relation fields (requires compatible form theme/template).')
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('translations')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->arrayNode('field_keys')
                            ->prototype('scalar')->end()
                            ->defaultValue(['label', 'placeholder'])
                        ->end()
                        ->arrayNode('patterns')
                            ->useAttributeAsKey('name')
                            ->prototype('scalar')->end()
                            ->defaultValue([])
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('live_table')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')
                            ->defaultFalse()
                        ->end()
                        ->enumNode('pagination_position')
                            ->values(['top', 'bottom', 'all'])
                            ->defaultValue('bottom')
                        ->end()
                        ->integerNode('default_per_page')
                            ->min(1)
                            ->defaultValue(25)
                        ->end()
                        ->integerNode('max_per_page')
                            ->min(1)
                            ->defaultValue(100)
                        ->end()
                    ->end()
                ->end()
            ->end()
        ;

        return $treeBuilder;
    }
}
